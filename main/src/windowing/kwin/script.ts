import type { ShortcutBinding } from "./types";

/**
 * Generators for KWin scripting-API scripts (Plasma 6). The scripts run
 * inside the compositor, where Wayland clients can still observe and move
 * windows. All events go out to the app over DBus (callDBus); the app
 * reaches back only by (re)loading generated script files.
 *
 * The KWin scripting environment has no timers and cannot receive DBus
 * signals, so commands from the app (activate overlay / focus game) are
 * static one-shot scripts whose body runs once when the script is started.
 */

function q(s: string): string {
  return JSON.stringify(s);
}

export function generateMainScript(params: {
  serviceName: string;
  dbusPath: string;
  dbusInterface: string;
  gameTitle: string;
  overlayTitle: string;
  shortcuts: ShortcutBinding[];
}): string {
  const shortcutList = params.shortcuts
    .map(([id, key]) => `  [${q(id)}, ${q(key)}]`)
    .join(",\n");

  return `// Generated by Exiled Exchange 2 - do not edit
// Game tracking, overlay placement/stacking, cursor and shortcut events.
var SERVICE = ${q(params.serviceName)};
var PATH = ${q(params.dbusPath)};
var IFACE = ${q(params.dbusInterface)};
var GAME_TITLE = ${q(params.gameTitle)};
var OVERLAY_TITLE = ${q(params.overlayTitle)};
var SHORTCUTS = [
${shortcutList}
];

var game = null;
var overlay = null;
var gameWasFs = false;
var gameRaised = false;

// While an app window is visible over a (latched) fullscreen game, keep the
// game itself above panels: KWin only gives the fullscreen layer to the
// active window, so an inactive fullscreen game would otherwise sit below
// the always-visible Plasma panels.
function recomputeGameLayer() {
  var want = overlay !== null && game !== null && gameWasFs;
  if (want) {
    if (!gameRaised) {
      game.keepAbove = true;
      gameRaised = true;
    }
  } else if (gameRaised) {
    gameRaised = false;
    if (game !== null && game.keepAbove === true) {
      game.keepAbove = false;
    }
  }
}

function call(method) {
  var args = Array.prototype.slice.call(arguments, 1);
  callDBus.apply(null, [SERVICE, PATH, IFACE, method].concat(args));
}

function roundedGeometry(window) {
  var g = window.frameGeometry;
  return [Math.round(g.x), Math.round(g.y), Math.round(g.width), Math.round(g.height)];
}

function onGameGeometry() {
  if (!game) return;
  if (overlay) {
    overlay.frameGeometry = game.frameGeometry;
  }
  var g = roundedGeometry(game);
  call.apply(null, ["Bounds"].concat(g));
}

function onGameActiveChanged() {
  if (!game) return;
  if (game.active) {
    call("Focus");
  } else {
    call("Blur");
  }
}

function onGameFullscreenChanged() {
  if (game) {
    // latch: the fullscreen flag drops while the overlay is active
    if (game.fullScreen === true) {
      gameWasFs = true;
    }
    recomputeGameLayer();
    call("Fullscreen", game.fullScreen === true);
  }
}

function connectGame(w) {
  game = w;
  gameWasFs = w.fullScreen === true;
  w.frameGeometryChanged.connect(onGameGeometry);
  w.activeChanged.connect(onGameActiveChanged);
  w.fullScreenChanged.connect(onGameFullscreenChanged);
  if (overlay) {
    overlay.frameGeometry = w.frameGeometry;
  }
  var g = roundedGeometry(w);
  call.apply(null, ["Attach", w.fullScreen === true].concat(g));
  recomputeGameLayer();
}

function disconnectGame() {
  var w = game;
  game = null;
  recomputeGameLayer();
  if (!w) return;
  w.frameGeometryChanged.disconnect(onGameGeometry);
  w.activeChanged.disconnect(onGameActiveChanged);
  w.fullScreenChanged.disconnect(onGameFullscreenChanged);
  call("Detach");
}

function connectOverlay(w) {
  overlay = w;
  w.keepAbove = true;
  w.skipTaskbar = true;
  if (game) {
    w.frameGeometry = game.frameGeometry;
  }
  recomputeGameLayer();
}

workspace.windowAdded.connect(function(w) {
  if (w.caption === GAME_TITLE && !game) {
    connectGame(w);
  } else if (w.caption === OVERLAY_TITLE && !overlay) {
    connectOverlay(w);
  }
});

workspace.windowRemoved.connect(function(w) {
  if (w === game) {
    disconnectGame();
  } else if (w === overlay) {
    overlay = null;
  }
  recomputeGameLayer();
});

workspace.cursorPosChanged.connect(function() {
  if (!game) return;
  var p = workspace.cursorPos;
  call("Cursor", Math.round(p.x), Math.round(p.y));
});

SHORTCUTS.forEach(function(binding) {
  registerShortcut(
    "Exiled Exchange 2 - " + binding[0],
    "Exiled Exchange 2 action: " + binding[0],
    binding[1],
    function() {
      call("Shortcut", binding[0]);
    }
  );
});

workspace.windowList().forEach(function(w) {
  if (!game && w.caption === GAME_TITLE) {
    connectGame(w);
  } else if (!overlay && w.caption === OVERLAY_TITLE) {
    connectOverlay(w);
  }
});
`;
}

/** One-shot body: give input focus to the overlay window. */
export function generateFocusOverlayScript(overlayTitle: string): string {
  return `// Generated by Exiled Exchange 2 - do not edit
var w = workspace.windowList().find(function(w) { return w.caption === ${q(overlayTitle)}; });
if (w) {
  workspace.activeWindow = w;
}
`;
}

/** One-shot body: give input focus back to the game window. */
export function generateFocusGameScript(gameTitle: string): string {
  return `// Generated by Exiled Exchange 2 - do not edit
var w = workspace.windowList().find(function(w) { return w.caption === ${q(gameTitle)}; });
if (w) {
  workspace.activeWindow = w;
}
`;
}

/**
 * One-shot body: release state the main script may have left behind — the
 * raised game window and any panels still pushed below.
 */
export function generateRestoreLayerScript(gameTitle: string): string {
  return `// Generated by Exiled Exchange 2 - do not edit
workspace.windowList().forEach(function (w) {
  if (w.caption === ${q(gameTitle)}) {
    w.keepAbove = false;
  } else if (w.dock === true) {
    w.keepBelow = false;
  }
});
`;
}
